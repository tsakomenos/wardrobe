const dicts: Record<Lang, Dict> = { el, en }

/** Translate a key in the current language, interpolating {params}. Unknown keys fall back to English, then the key itself. */
export function t(key: string, params?: Record<string, string | number>): string {
  let s = dicts[current][key] ?? en[key] ?? key
  if (params) for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(String(v))
  return s
}

/** English fallback for data labels that have no translation entry (e.g. a subtype added later). */
export function tOr(key: string, fallback: string): string {
  return dicts[current][key] ?? fallback
}
