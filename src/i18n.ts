export type Lang = 'el' | 'en'

const LANG_KEY = 'wardrobe.lang'

let current: Lang = (() => {
  try {
    const v = localStorage.getItem(LANG_KEY)
    return v === 'en' ? 'en' : 'el'
  } catch {
    return 'el'
  }
})()

export function getLang(): Lang {
  return current
}

export function setLang(l: Lang) {
  current = l
  try {
    localStorage.setItem(LANG_KEY, l)
  } catch {
    /* ignore */
  }
}

